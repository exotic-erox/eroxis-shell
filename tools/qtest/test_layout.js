const fs = require("fs"), vm = require("vm"), assert = require("assert");
const ctx = {}; vm.createContext(ctx);
vm.runInContext(fs.readFileSync("" + require("path").resolve(__dirname, "../../shell/config/ControlLayout.js") + "", "utf8").replace(/^\.pragma.*$/m, "") + ";this.L = { clean, join, move, setShown, width, sections, defaultSections, tiles, defaultTiles };", ctx);
const L = ctx.L; let n = 0;
const eq = (a, b) => { assert.deepStrictEqual(JSON.parse(JSON.stringify(a)), JSON.parse(JSON.stringify(b))); n++; };
eq(L.clean(undefined, L.sections, L.defaultSections), L.defaultSections);
eq(L.clean(null, L.sections, L.defaultSections), L.defaultSections);
eq(L.clean(["tiles", "bogus", "tiles", "media"], L.sections, L.defaultSections), ["tiles", "media"]);
eq(L.clean([], L.sections, L.defaultSections), []);
eq(L.clean({ 0: "media", length: 1 }, L.sections, L.defaultSections), ["media"]);
eq(L.clean("media", L.sections, L.defaultSections), ["media"]);
eq(L.clean("media,tiles,bogus,tiles", L.sections, L.defaultSections), ["media", "tiles"]);
eq(L.clean("", L.sections, L.defaultSections), []);
eq(L.clean(5, L.sections, L.defaultSections), L.defaultSections);
eq(L.join(["a", "b"]), "a,b"); eq(L.join([]), "");
eq(L.move(["a", "b", "c"], "b", -1), ["b", "a", "c"]);
eq(L.move(["a", "b", "c"], "a", -1), ["a", "b", "c"]);
eq(L.move(["a", "b", "c"], "c", 1), ["a", "b", "c"]);
eq(L.move(["a", "b", "c"], "x", 1), ["a", "b", "c"]);
eq(L.setShown(["a", "b"], "c", true), ["a", "b", "c"]);
eq(L.setShown(["a", "b"], "a", true), ["b", "a"]);
eq(L.setShown(["a", "b"], "a", false), ["b"]);
eq(L.width(560), 560); eq(L.width(999), 480); eq(L.width(undefined), 480);
assert(L.defaultSections.every(x => L.sections.includes(x)) && L.defaultTiles.every(x => L.tiles.includes(x))); n++;
console.log("ControlLayout.js:", n, "checks passed");
